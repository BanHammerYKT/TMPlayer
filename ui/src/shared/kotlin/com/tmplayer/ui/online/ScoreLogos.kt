    private fun logo(name: String, width: Float, height: Float, vararg parts: Pair<Long, String>): ImageVector {
        val builder = ImageVector.Builder(
            name = name,
            defaultWidth = width.dp,
            defaultHeight = height.dp,
            viewportWidth = width,
            viewportHeight = height,
        )
        for ((argb, d) in parts) {
            builder.addPath(pathData = PathParser().parsePathString(d).toNodes(), fill = SolidColor(Color(argb)))
        }
        return builder.build()
    }
